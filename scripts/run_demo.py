"""Play Arjun's 42 days through the real Iris engine and save what each screen shows.

Days 1 to 14 only learn his normal (no model calls). From day 15, every day is
one live Muse read of his day, then one note per friend whose setting allows it,
each written blind and checked twice. The output (web/demo_data.js) lets the
screens run offline for the video. Its shape is documented at the top of the file.

Usage: python3 scripts/run_demo.py
"""

import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from engine import muse  # noqa: E402
from engine.decide import decide  # noqa: E402
from engine.day import MOODS  # noqa: E402
from engine.demo import Demo  # noqa: E402

OUT = ROOT / "web" / "demo_data.js"

HEADER = """// Iris demo data. Generated by scripts/run_demo.py from the real engine (Muse calls are live).
// Everything is fictional: Arjun, his 5, his messages, his calendar and his Spotify.
//
// window.DEMO = {
//   version: 2, owner: "Arjun", interests: [...], settings: {note_time, send_mode, sources, circle: [...]},
//   days: [{
//     n, date, weekday, learning,              // learning: days 1-14, no read, no notes
//     mood, direction, moment, size, why,      // the day read: mood word, its direction (up | flat | down), the
//                                              // general moment, ordinary | notable | big, a private why (his log only)
//     notes: [{to, text, interest, signature, status, sends_at, cancel_until, fallback, tries, check,
//              action: {type: song|reel|lunch|tickets|treat|message, label, detail, surprise, when?, suggested}}],
//     not_sent: [{name, why}], cards: [{kind, text}], prompts: [{kind, about, text}], log: [...],
//     inputs: {see, hear, talk, happens, normal},   // the day exactly as Muse read it (his own side only)
//     friend_view: [{name, mood, direction, source}],  // the friend's main view: the 5 and how each feels today.
//                                              // Arjun's mood comes from the engine (source "engine"); his
//                                              // friends' moods are SIMULATED (source "simulated"), as if they
//                                              // used Iris too. null mood on Arjun's learning days.
//     orbit, signals, families, rule           // how today compares with Arjun's own normal
//   }]
// }
"""


# SIMULATED moods for Arjun's 5, as if each of them used Iris too. Fixed seed, a few story beats.
FRIEND_MOOD_POOL = {"okay": 5, "calm": 4, "happy": 4, "busy": 3, "content": 2, "tired": 3, "excited": 1,
                    "stressed": 1, "low": 1}
FRIEND_BEATS = {("Maya", 31): "happy", ("Maya", 32): "happy", ("Maya", 33): "happy", ("Maya", 36): "proud",
                ("Sam", 36): "excited", ("Omar", 38): "excited", ("Maya", 23): "calm"}


def friend_mood(name, n):
    mood = FRIEND_BEATS.get((name, n))
    if not mood:
        rng = random.Random(f"{name}-{n}")
        mood = rng.choices(list(FRIEND_MOOD_POOL), weights=list(FRIEND_MOOD_POOL.values()), k=1)[0]
    return mood


def friend_view(demo, n, mood):
    people = [{"name": demo.first, "mood": mood, "direction": MOODS.get(mood) if mood else None, "source": "engine"}]
    for m in demo.settings["circle"]:
        first = m["name"].split()[0]
        fm = friend_mood(first, n)
        people.append({"name": first, "mood": fm, "direction": MOODS[fm], "source": "simulated"})
    return people


def main():
    demo = Demo()
    n = len(demo.days)
    before = muse.spent()
    print(f"{demo.first}: {n} days, spend so far ${before:.2f}")
    recent, days = {}, []
    for i in range(n):
        sit = demo.situation(i, recent_notes={k: v[-3:] for k, v in recent.items()})
        out = decide(sit)
        for note in out["notes"]:
            recent.setdefault(note["to"], []).append(note["text"])
        rule = demo.rule[i]
        r = out["read"] or {}
        notes = [dict({k: note.get(k) for k in ("to", "text", "interest", "action", "signature", "status",
                                                "sends_at", "cancel_until", "fallback")},
                      tries=len(note["attempts"]),
                      check=note["attempts"][-1].get("check") if note["attempts"] else None)
                 for note in out["notes"]]
        days.append({
            "n": i + 1, "date": demo.days[i], "weekday": sit["day"]["weekday"], "learning": i + 1 <= 14,
            "mood": out["mood"], "direction": r.get("direction"), "moment": r.get("moment"), "size": out["size"],
            "why": r.get("why", ""),
            "notes": notes, "not_sent": out["not_sent"], "cards": out["cards"], "prompts": out["prompts"],
            "log": out["log"],
            "inputs": {k: sit["day"].get(k) for k in ("see", "hear", "talk", "happens", "normal")},
            "friend_view": friend_view(demo, i + 1, out["mood"]),
            "orbit": demo.orbit(i),
            "signals": sit["day"]["normal"],
            "families": rule.get("families", []),
            "rule": "heavy" if rule["heavy_stretch"] else ("lighter" if rule["lighter_stretch"] else
                    ("learning" if rule["learning"] else "normal")),
        })
        print(f"{i + 1:>2} {out['mood'] or '-':<9}{out['size'] or '-':<9}{(r.get('moment') or ''):<22}" +
              " | ".join(f"{x['to']}: [{x['action']['type']}{'*' if x['action']['surprise'] else ''}] {x['text']}"
                         for x in notes), flush=True)

    data = {"version": 2, "owner": demo.first, "interests": demo.interests, "settings": demo.settings, "days": days}
    OUT.write_text(HEADER + "window.DEMO = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), f"spend ${before:.2f} -> ${muse.spent():.2f}")


if __name__ == "__main__":
    main()
